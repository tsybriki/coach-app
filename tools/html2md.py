#!/usr/bin/env python3
"""
html2md.py — разовая односторонняя конвертация HTML-спецификации в MD.

Запуск:
    python3 tools/html2md.py DOMAIN-SPEC.html specs/domain/DOMAIN-SPEC.md

Зачем: раньше источником правды был HTML, а MD собирался из него скриптом.
Теперь наоборот — источник правды MD, а HTML собирается из MD.

Этот скрипт нужен один раз: чтобы перевернуть существующую спецификацию.
Дальше правится MD, а HTML пересобирается через render_spec.py.

Что переносится:
  - все сущности, связи, таблицы, инварианты, решения, вопросы
  - отметки подтверждения инвариантов (class="confirmed")
  - SVG-диаграмма — в отдельный файл assets, в MD вставляется ссылка
  - счётчики и версия в шапке
"""
from __future__ import annotations

import html
import os
import re
import sys


def strip_tags(s: str) -> str:
    s = re.sub(r'<code>(.*?)</code>', r'`\1`', s, flags=re.S)
    s = re.sub(r'<[^>]+>', '', s)
    s = html.unescape(s)
    return re.sub(r'\s+', ' ', s).strip()


def md_table(rows: list[list[str]]) -> str:
    if not rows:
        return ""
    head = "| " + " | ".join(rows[0]) + " |"
    sep = "|" + "|".join(["---"] * len(rows[0])) + "|"
    body = "\n".join("| " + " | ".join(r) + " |" for r in rows[1:])
    return head + "\n" + sep + "\n" + body


def table_after(src: str, anchor: str) -> list[list[str]]:
    i = src.index(anchor)
    m = re.search(r'<table>(.*?)</table>', src[i:], re.S)
    if not m:
        return []
    rows = []
    for tr in re.findall(r'<tr>(.*?)</tr>', m.group(1), re.S):
        cells = [strip_tags(c) for c in re.findall(r'<t[hd][^>]*>(.*?)</t[hd]>', tr, re.S)]
        if cells:
            rows.append(cells)
    return rows


def main() -> int:
    if len(sys.argv) < 3:
        print("usage: html2md.py <вход.html> <выход.md>")
        return 1
    src_path, out_path = sys.argv[1], sys.argv[2]
    src = open(src_path, encoding="utf-8").read()
    out: list[str] = []
    A = out.append

    # --- шапка ---
    hdr = re.search(
        r'<div class="meta">Coach App · (v[\d.]+) · (\d+) сущностей · (\d+) инвариантов '
        r'\((\d+) подтверждено\) · (\d+) вопросов</div>', src)
    version, n_ent, n_inv, n_ok, n_q = hdr.groups()

    A("# Модель домена — спецификация")
    A("")
    A(f"Coach App · {version} · {n_ent} сущностей · {n_inv} инвариантов ({n_ok} подтверждено) · {n_q} вопросов")
    A("")
    A("> **Источник правды:** этот MD-файл. HTML — производная: `python3 tools/render_spec.py`.")
    A("> Правки вносятся здесь, HTML пересобирается.")
    A("")

    # --- 1 диаграмма ---
    A("## 1 · Диаграмма сущностей")
    A("")
    svg_m = re.search(r'(<svg viewBox="0 0 380 1024">.*?</svg>)', src, re.S)
    if svg_m:
        assets_dir = os.path.join(os.path.dirname(out_path), "assets")
        os.makedirs(assets_dir, exist_ok=True)
        svg_path = os.path.join(assets_dir, "domain-diagram.svg")
        with open(svg_path, "w", encoding="utf-8") as f:
            f.write(svg_m.group(1))
        A("![Диаграмма сущностей](assets/domain-diagram.svg)")
        A("")
        A("Вложенность = владение. Пунктир красный — переопределение слота или сопоставление "
          "план↔факт. Пунктир серый — ссылка на справочник. Блок «ФАКТ» — данные, приходящие "
          "извне плана.")
        A("")

    # --- 2 сущности ---
    A("## 2 · Сущности")
    A("")
    ents = re.findall(
        r'<div class="ent">\s*<div class="eh"><span>(.*?)</span><span class="k">(.*?)</span></div>\s*'
        r'(?:<ul class="role">(.*?)</ul>\s*)?<ul class="pl">(.*?)</ul>\s*</div>', src, re.S)
    for name, kind, role, body in ents:
        A(f"### {name}  *({kind})*")
        A("")
        if role:
            A(strip_tags(role))
            A("")
        for li in re.findall(r'<li>(.*?)</li>', body, re.S):
            A(f"- {strip_tags(li)}")
        A("")

    # --- 3 связи ---
    A("## 3 · Связи")
    A("")
    A("### Владение и ссылки")
    A("")
    A(md_table(table_after(src, '<section id="r">')))
    A("")
    A("### Наследование слотов")
    A("")
    A(md_table(table_after(src, '<h3>Наследование слотов</h3>')))
    A("")
    A("Итог: `Season ← Phase ← Week`, каждое перекрытие применяется последним. "
      "Patch хранит только отличие от уровня выше.")
    A("")

    # --- инварианты ---
    A("### Инварианты")
    A("")
    inv_block = src[src.index("<h3>Инварианты</h3>"):src.index("<h3>Производные значения</h3>")]
    inv_rows = []
    for m in re.finditer(r'<tr([^>]*)><td class="n">(I\d+)</td><td class="st">.*?</td><td>(.*?)</td></tr>',
                         inv_block, re.S):
        cls, num, text = m.groups()
        mark = " ✓" if "confirmed" in cls else ""
        inv_rows.append([num, strip_tags(text) + mark])
    A(md_table([["#", "Правило"]] + inv_rows))
    A("")
    A("Отметка `✓` = подтверждено Кириллом. При подтверждении правится эта отметка, "
      "не текст правила.")
    A("")

    # --- решения ---
    A("### Решения по вопросам")
    A("")
    A("Зафиксированные ответы Кирилла. Действуют как правила модели.")
    A("")
    A(md_table(table_after(src, '<h3>Решения по вопросам</h3>')))
    A("")

    # --- производные ---
    A("### Производные значения")
    A("")
    A("Не хранятся — считаются.")
    A("")
    A(md_table(table_after(src, '<h3>Производные значения</h3>')))
    A("")

    # --- жизненный цикл ---
    A("### Жизненный цикл недели")
    A("")
    A("Три состояния. Всё инициирует пользователь. Изменений назад нет: прошедшие сессии "
      "не трогаются, закрытая неделя не переоткрывается.")
    A("")
    A(md_table(table_after(src, '<h3>Жизненный цикл недели</h3>')))
    A("")

    A("#### propose_week — можно вызывать многократно")
    A("")
    A("Планировщик берёт макро фазы, собирает намерения и раскладывает их по слотам. Всё, "
      "что не разложилось, уходит в **ручной режим** — `unplaced[]`. Каждый новый propose "
      "**вытирает предыдущий**: неделю можно предлагать заново, пока она не активна.")
    A("")
    A("#### activate_week — неделя оживает")
    A("")
    A("Все тренировки, которые удалось разложить, стоят по слотам. То, что не разложилось, "
      "**остаётся висеть** в `unplaced[]` — расписание не обязано быть жёстким. Дальше неделя "
      "живёт: тренировки выполняются, факт привязывается, висялки можно разложить позже "
      "командой `place_unplaced`.")
    A("")
    A("#### close_week — явный ритуал")
    A("")
    A("Считаем саммари, записываем. После этого неделя закрыта и **не меняется**: ни новый "
      "факт, ни поздняя активность её не трогают. Дальше планируется следующая неделя.")
    A("")
    A("#### replan_remainder — переплан остатка")
    A("")
    A("Внутри недели можно запросить перепланирование **остатка**: сессии на сегодня и позже. "
      "Прошедшие сессии не меняются. Запрос инициирует пользователь.")
    A("")
    A("**Что из этого следует**")
    A("")
    A("1. Черновик не считается: `proposed` не влияет на расчёт нагрузки до активации.")
    A("2. Висяки (`unplaced[]`) допустимы в любом состоянии, включая `active`. Расписание "
      "мягкое: лучше оставить тренировку неразложенной, чем насильно приткнуть её в "
      "неподходящий слот.")
    A("3. Висящая тренировка не выполнена, но и не отменена — она ждёт места. Отличие от "
      "`missed` в саммари: `missed` — тренировка стояла по слоту, но не выполнена.")
    A("4. Закрытие — всегда ручное действие. Автоматика может предложить, но не закрыть.")
    A("5. Никаких отмен и откатов: активированная неделя живёт до закрытия, закрытая — навсегда.")
    A("")
    A("#### Что появляется на каждом шаге")
    A("")
    A(md_table(table_after(src, '<h4>Что появляется на каждом шаге</h4>')))
    A("")
    A("#### Порядок внутри close_week")
    A("")
    A("`вытянуть остаток факта → сопоставить руками → посчитать и записать`. Неподтверждённые "
      "сессии не блокируют закрытие — они попадают в саммари как `missed`. Переносов в "
      "следующую неделю нет.")
    A("")
    A("### Висяки и план недели")
    A("")
    A("Решение по висякам — **за пользователем**: он остаётся висеть и учитывается в плане "
      "недели. Факт всё равно берётся из факта. При закрытии недели сравниваем план с фактом.")
    A("")
    A("### Связывание факта и плана")
    A("")
    A("Автоматического сопоставления нет вообще. Факт и план связывает пользователь, вручную.")
    A("")
    A("**Цель связывания** — сопоставить задачу сессии с её выполнением. Всё, что не связано, "
      "в любом случае учитывается в actuals: связывание уточняет отчёт, но не решает, что "
      "считать сделанным.")
    A("")
    A("**Активности берутся только из Garmin.** Поздний факт (пришедший после закрытия недели) "
      "игнорируется — закрытые недели не трогаются.")
    A("")
    A(md_table(table_after(src, '<h3>Связывание факта и плана</h3>')))
    A("")
    A("### Закрытие недели")
    A("")
    A("Простой явный ритуал, три шага.")
    A("")
    A("**Планирование и выполнение** — всё, что попало в план до активации, считается "
      "планированием. Всё, что планировалось, но к моменту закрытия не связано с фактом, — "
      "не выполнено.")
    A("")
    A("**Закрытие — только по команде**, само ничего не закрывается. Недель с переносами между "
      "собой нет: закрываем одну, потом планируем следующую.")
    A("")
    A(md_table(table_after(src, '<h3>Закрытие недели</h3>')))
    A("")
    A("### Неделя в работе")
    A("")
    A(md_table(table_after(src, '<h3>Неделя в работе</h3>')))
    A("")

    # --- вопросы ---
    A("## 4 · Вопросы")
    A("")
    qs = re.findall(r'<li>(.*?)</li>',
                    src[src.index('<ol class="probs">'):src.index("</ol>", src.index('<ol class="probs">'))],
                    re.S)
    for i, q in enumerate(qs, 1):
        A(f"{i}. {strip_tags(q)}")
    A("")

    A("---")
    A("")
    A(f"Coach App · модель домена {version}")
    A("")

    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))

    print(f"written: {out_path} ({os.path.getsize(out_path)} bytes)")
    print(f"entities={len(ents)} invariants={len(inv_rows)} questions={len(qs)} "
          f"confirmed={sum(1 for r in inv_rows if r[1].endswith('✓'))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
