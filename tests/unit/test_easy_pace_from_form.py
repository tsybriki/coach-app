"""Лёгкий темп — производная от формы, а не зашитое число.

Кирилл (26.11.2026): «VDOT везде поставить 49 и обновить темпы. Эту
неделю не трогать».

Зачем это правило. До сих пор лёгкий бег шёл по **зашитой константе**
5:40 — решению по спортсмену, принятому 18.11.2026, когда форма была
VDOT 48. Но 5:40 — это не отдельное число, а **«E» из таблицы Дэниэлса
плюс 12 секунд**:

    VDOT 48: E = 328 с/км (5:28)  + 12 = 340 с/км (5:40)
    VDOT 49: E = 323 с/км (5:23)  + 12 = 335 с/км (5:35)

Смысл тот же, что был в исходном решении: «E» из таблицы — **верх**
лёгкой зоны, и на длинной дистанции в нём пульс упирается в верх Z2,
а «лёгкий бег» перестаёт быть лёгким. Середина зоны — плюс 12 секунд.

**Почему это не «просто посчитать по таблице».** Если оставить
константу 5:40, то при росте формы лёгкий бег останется на прежнем
темпе: план перестанет соответствовать форме, а карточка профиля и
план будут показывать разное. Константа — это отложенная ошибка.

Что проверяется:

- лёгкий темп считается от зоны «E» текущей формы плюс 12 секунд;
- при VDOT 48 это 5:40 (как было), при VDOT 49 — 5:35;
- без формы или без справочника темпа нет — это «не задано», а не ноль;
- остальные зоны берутся из таблицы как есть.

Имя тестов: `test_i52_...` — инвариант I52 из спецификации.
"""
from __future__ import annotations

from pathlib import Path

from app.adapters.daniels import load_paces
from app.domain.entities import Athlete
from app.domain.methodology import (
    EASY_PACE_OFFSET_SEC,
    form_paces,
)

REPO = Path(__file__).resolve().parent.parent.parent
REFERENCE = REPO / "reference" / "daniels"

HR_ZONES = {
    "Z1": (100, 118),
    "Z2": (118, 135),
    "Z3": (136, 150),
    "Z4": (150, 160),
    "Z5": (160, 168),
    "Z6": (169, 172),
    "Z7": (173, 182),
}


def athlete(vdot: float) -> Athlete:
    return Athlete(vdot=vdot, hr_zones=HR_ZONES, hr_max=182, rhr=54, lth=164)


# ------------------------------------------------------------------ I52


def test_i52_easy_pace_is_table_plus_offset():
    """I52: лёгкий темп — «E» текущей формы плюс 12 секунд.

    5:40 при VDOT 48 — это не отдельное решение, а 328 + 12. Правило
    одно на все формы: с ростом формы лёгкий бег ускоряется сам.
    """
    paces = load_paces(REFERENCE)

    for vdot, expected in ((48.0, "5:40"), (49.0, "5:35")):
        result = form_paces(athlete(vdot), paces)
        assert result["E"] == expected, (
            f"при VDOT {vdot:.0f} лёгкий темп {result['E']}, а ожидался {expected}"
        )


def test_i52_easy_pace_offset_is_twelve_seconds():
    """I52: смещение от «E» — 12 секунд на километр.

    Это то самое решение 18.11.2026, выраженное формулой: «E» из
    таблицы — верх лёгкой зоны, середина — плюс 12 секунд.
    """
    assert EASY_PACE_OFFSET_SEC == 12.0


def test_i52_easy_pace_follows_form():
    """I52: с ростом формы лёгкий темп ускоряется.

    Иначе план остался бы на прежнем темпе, и карточка профиля
    показывала бы одно, а план — другое.
    """
    paces = load_paces(REFERENCE)

    at_48 = form_paces(athlete(48.0), paces)["E"]
    at_49 = form_paces(athlete(49.0), paces)["E"]

    assert at_48 == "5:40"
    assert at_49 == "5:35"
    assert at_49 != at_48, "форма выросла, а лёгкий темп остался прежним"


def test_i52_other_zones_come_from_table():
    """I52: остальные зоны — из таблицы, без смещения.

    Смещение 12 секунд — только про лёгкую зону. Темпы отрезков и
    тестов не трогаем: там темп и есть содержание работы.
    """
    paces = load_paces(REFERENCE)

    result = form_paces(athlete(49.0), paces)

    # Таблица для VDOT 49: порог 260 (4:20), интервал 239 (3:59),
    # повторный 222 (3:42), марафонский 276 (4:36).
    assert result["T"] == "4:20"
    assert result["I"] == "3:59"
    assert result["R"] == "3:42"
    assert result["M"] == "4:36"


def test_i52_no_form_means_no_paces():
    """I52: без формы лёгкого темпа нет — это «не задано», а не ноль.

    Профиль без VDOT — пустой профиль, а не ошибка.
    """
    paces = load_paces(REFERENCE)

    result = form_paces(athlete(0.0), paces)

    assert result == {}


def test_i52_no_reference_means_no_paces():
    """I52: без справочника темпов нет, и ошибки не происходит."""
    result = form_paces(athlete(49.0), None)

    assert result == {}
